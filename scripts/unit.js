// Unit tests for guess matching and scoring: node scripts/unit.js
const { judge, mask } = require('../lib/match');
const { guessPoints, pickerPoints } = require('../lib/scoring');
const words = require('../lib/words');
let pass = 0, fail = 0;
const eq = (a, b, m) => { if (a === b) { pass++; console.log('  PASS', m); } else { fail++; console.log('  FAIL', m, '->', a, 'expected', b); } };
const J = (g, w, al = []) => judge(g, [w, ...al]);
console.log('Matching');
eq(J('Happy', 'happy'), 'correct', 'case-insensitive');
eq(J('  happy!! ', 'happy'), 'correct', 'punctuation + spaces');
eq(J('the road trip', 'road trip'), 'correct', 'leading article ignored');
eq(J('roadtrip', 'road trip'), 'correct', 'spacing tolerance');
eq(J('adventures', 'adventure'), 'correct', 'plural');
eq(J('nostalgic', 'nostalgic'), 'correct', 'exact');
eq(J('nostalgik', 'nostalgic'), 'correct', 'one typo on a long word');
eq(J('nostalgcii', 'nostalgic') !== 'correct', true, 'two typos on a 9-letter word are not accepted');
eq(J('mad', 'sad'), 'wrong', 'short neighbours are distinct');
eq(J('dense', 'tense') !== 'correct', true, 'short neighbours are distinct (5 letters)');
eq(J('i think its joy', 'joy'), 'correct', 'answer inside a sentence');
eq(J('anger', 'angry', ['anger']), 'correct', 'alias');
eq(J('nostalgi', 'nostalgic'), 'correct', 'missing letter');
eq(J('wedding day', 'wedding'), 'correct', 'whole word contained');
eq(J('weddings', 'wedding'), 'correct', 'plural');
eq(J('sorrowful', 'mournful'), 'wrong', 'unrelated');
eq(J('', 'happy'), 'wrong', 'empty');
eq(J('melancholi', 'melancholy'), 'correct', 'typo');
eq(J('melancoly', 'melancholy'), 'correct', 'typo 2');
eq(mask('road trip'), '____ ____', 'mask keeps word lengths');
eq(mask('self-conscious'), '____-_________', 'mask keeps hyphens');
console.log('Scoring');
eq(guessPoints(90000, 90000, 1), 500, 'instant guess on song 1 = 500');
eq(guessPoints(90000, 0, 1), 100, 'last-second guess on song 1 = 100');
eq(guessPoints(90000, 90000, 3) < guessPoints(90000, 90000, 1), true, 'later songs are worth less');
eq(guessPoints(90000, 45000, 1) > guessPoints(90000, 20000, 1), true, 'sooner is worth more');
eq(pickerPoints(400), 100, 'picker earns a quarter');
console.log('Words');
for (const [k, v] of Object.entries(words.CATEGORIES)) eq(v.length >= 150, true, `${k} has ${v.length} words`);
eq(Object.values(words.CATEGORIES).flat().every((w) => w.word.length >= 3 && w.word.length <= 30), true, 'word lengths are sane');
console.log(`\n${pass} passed, ${fail} failed`); process.exit(fail ? 1 : 0);
